#!/usr/bin/env node
// Regenerate src/content/gameLanguages.ts from the game's LanguageManager, so
// the translation-report dropdown always offers exactly the languages the game
// ships. Run after adding a language to the game:
//   node scripts/gen-game-languages.mjs [path/to/geofast/Managers/LanguageManager.gd]
//
// The game tells Spanish and Portuguese variants apart by flag; a dropdown
// needs words, hence REGION. Two entries with the same label fail the run.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const GAME = resolve(ROOT, "..", "geofast");
const SOURCE = process.argv[2] ?? join(GAME, "Managers", "LanguageManager.gd");
const OUT = join(ROOT, "src", "content", "gameLanguages.ts");

const REGION = {
  "es-ES": "España",
  "es-LA": "Latinoamérica",
  "pt-BR": "Brasil",
  "pt-PT": "Portugal",
};

const gd = readFileSync(SOURCE, "utf8");
const start = gd.indexOf("static var languages := {");
const end = gd.indexOf("\n}", start);
if (start < 0 || end < 0) throw new Error(`languages dictionary not found in ${SOURCE}`);
const entries = [...gd.slice(start, end).matchAll(/"code":\s*"([^"]+)",\s*"display":\s*"([^"]+)"/g)].map(([, code, name]) => ({
  code,
  name: REGION[code] ? `${name} (${REGION[code]})` : name,
}));
if (entries.length < 50) throw new Error(`only ${entries.length} languages parsed; format changed?`);

// Every language the game ships as a .po must be offered, and nothing else.
const poDir = join(GAME, "Assets", "translations");
if (existsSync(poDir)) {
  const po = new Set(readdirSync(poDir).filter((f) => f.endsWith(".po")).map((f) => f.slice(0, -3)));
  const codes = new Set(entries.map((e) => e.code));
  const missing = [...po].filter((c) => !codes.has(c));
  const extra = [...codes].filter((c) => !po.has(c));
  if (missing.length || extra.length) throw new Error(`mismatch with .po files: missing ${missing}, extra ${extra}`);
}

const labels = new Set();
for (const e of entries) {
  if (labels.has(e.name)) throw new Error(`duplicate label "${e.name}"; add a REGION entry for ${e.code}`);
  labels.add(e.name);
}

// Sorted by native name so a player finds their own language by eye.
entries.sort((a, b) => a.name.localeCompare(b.name, undefined, { sensitivity: "base" }));

const lines = entries.map((e) => `  { code: ${JSON.stringify(e.code)}, name: ${JSON.stringify(e.name)} },`);
writeFileSync(
  OUT,
  `// Generated by scripts/gen-game-languages.mjs from the game's LanguageManager.gd
// (code and native display name; Spanish and Portuguese variants carry their
// region). Used by the translation-report form. Do not edit by hand: rerun the
// script when the game adds a language.
export interface GameLanguage { code: string; name: string }
export const gameLanguages: GameLanguage[] = [
${lines.join("\n")}
];
`,
);
console.log(`wrote ${entries.length} languages to ${OUT}`);
